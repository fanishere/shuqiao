#!/usr/bin/env python3
# Regenerate board/*.md from a SEARCH_ISSUES result (paste JSON below).
import json, sys, os

data = json.load(open(sys.argv[1]))
issues = [it for it in data["issues"]
          if (it.get("issue_type") or {}).get("name") != "Epic"
          and (it.get("status") or {}).get("name") != "Done"]
keys = {it["key"] for it in issues}
board = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.makedirs(board, exist_ok=True)

index = ["<!-- AUTO-GENERATED by board/scripts/pull.py — do not edit by hand -->",
         "| Key | Summary | Status | Labels | Dirty |",
         "|-----|---------|--------|--------|-------|"]

for it in issues:
    st = it.get("status") or {}
    asg = it.get("assignee") or {}
    labels = it.get("labels") or []
    desc = (it.get("description") or "").strip() or "(no description)"
    card = f"""---
key: {it['key']}
id: "{it['id']}"
type: {(it.get('issue_type') or {}).get('name','Task')}
status: {st.get('name','')}
labels: {json.dumps(labels)}
assignee: {asg.get('display_name','') or 'unassigned'}
priority: {(it.get('priority') or {}).get('name','')}
updated: {it.get('updated','')}
dirty: false
---

# {it['key']} — {it['summary']}

{desc}

## Pending changes (local, not yet flushed to Jira)

(none)

<!-- Agents: record local writes here, one per line, and set dirty: true above.
     Op lines (timestamp optional, order preserved):
       - transition: <status name>          (e.g. - transition: In Progress)
       - comment: <markdown text>           (single line, or see artifacts below)
       - artifact: <absolute path>          (file to attach on flush)
       - label-add: <label> / label-remove: <label>
     Status frontmatter must be updated to match the last transition op.
     The flush agent consumes and clears this section. -->
"""
    with open(os.path.join(board, f"{it['key']}.md"), "w") as f:
        f.write(card)
    index.append(f"| [{it['key']}]({it['key']}.md) | {it['summary']} | {st.get('name','')} | {', '.join(labels) or '—'} | no |")

with open(os.path.join(board, "INDEX.md"), "w") as f:
    f.write("\n".join(index) + "\n")

# remove stale cards not in this pull (skip dirty ones — they hold unflushed ops)
import glob, re
for path in glob.glob(os.path.join(board, "SHU-*.md")):
    key = os.path.basename(path)[:-3]
    if key not in keys:
        body = open(path).read()
        if re.search(r"^dirty: true", body, re.M):
            print(f"kept dirty stale card {key}")
        else:
            os.remove(path)
            print(f"removed stale card {key}")
print(f"wrote {len(issues)} cards + INDEX.md")
